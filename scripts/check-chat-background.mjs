import assert from 'node:assert/strict';
import {request,env} from './check-education.mjs';
const ref=await env.DB.prepare("SELECT reference FROM education_enrolments WHERE user_id='learner-test'").first();await request('/api/chat/students',{method:'POST',account:'owner',data:{reference:ref.reference}});
const rows=(await env.DB.prepare('SELECT id FROM chat_students ORDER BY id').all()).results;const a=rows[0].id,b=rows[1].id;
const path='/api/chat/background';
const read=id=>request(path+'?student='+id,{account:'owner'});
const save=(id,data,account='owner')=>request(path,{method:'PUT',account,data:{studentId:id,...data}});
assert.deepEqual((await read(a)).data.background,{color:null,pattern:'dots',revision:0});
assert.equal((await save(a,{color:'#321b29',pattern:'grid',revision:0},'learner')).status,401);
assert.equal((await save(a,{color:'url(https://bad.test)',pattern:'grid',revision:0})).status,400);
assert.equal((await save(a,{color:'#321b29',pattern:'grid',revision:0})).status,200);
assert.equal((await save(a,{color:'#121820',pattern:'dots',revision:0})).status,409);
assert.equal((await read(b)).data.background.color,null);
const issued=await request('/api/chat/students',{method:'POST',account:'owner',data:{studentId:a}});
const session=await request('/api/chat/session',{method:'POST',data:{code:issued.data.code}});const cookie=session.headers.get('set-cookie').split(';')[0];
assert.equal((await request('/api/chat/messages',{cookie})).data.background.color,'#321b29');
assert.equal((await request(path,{method:'PUT',cookie,data:{studentId:a,color:'#ffffff',pattern:'plain',revision:1}})).status,403);
assert.equal((await request('/api/chat/messages?student='+b,{cookie})).status,403);
assert.equal((await save(a,{color:null,pattern:'dots',revision:1})).status,200);
assert.equal((await request('/api/chat/messages',{cookie})).data.background.color,null);
console.log('Background checks passed: owner-only changes, validation, per-chat isolation, student sync, revision conflicts and reset.');
