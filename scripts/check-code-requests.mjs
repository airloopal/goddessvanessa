import assert from 'node:assert/strict';
import {request,env} from './check-education.mjs';
const target=await env.DB.prepare("SELECT id FROM chat_students WHERE user_id='other-test'").bind().first();
const issued=await request('/api/chat/students',{method:'POST',account:'owner',data:{studentId:target.id}});
const login=await request('/api/chat/session',{method:'POST',data:{code:issued.data.code}});
const cookie=login.headers.get('set-cookie').split(';')[0];
const student=(method='GET',data)=>request('/api/chat/request-code',{method,cookie,data});
const review=(r,decision)=>request('/api/chat/code-requests',{method:'PATCH',account:'owner',data:{studentId:target.id,requestId:r.id,decision}});
assert.equal((await student()).data.request,null);
assert.equal((await request('/api/chat/code-requests',{cookie})).status,403);
assert.equal((await request('/api/chat/request-code',{method:'POST',data:{studentId:target.id}})).status,403);
assert.equal((await student('POST',{action:'collect'})).status,409);
const r=(await student('POST',{})).data.request;
assert.equal(r.status,'pending');assert.equal((await student('POST',{})).data.request.id,r.id);
assert.equal((await request('/api/chat/code-requests',{account:'owner'})).data.requests[0].studentId,target.id);
assert.equal((await request('/api/chat/request-code',{method:'POST',cookie,origin:'https://evil.test',data:{}})).status,403);
assert.equal((await review(r,'declined')).status,200);
assert.equal((await student()).data.request.status,'declined');
assert.equal((await student('POST',{action:'collect'})).status,409);
assert.equal((await request('/api/chat/session',{cookie})).status,200);
const second=(await student('POST',{})).data.request;
const decisions=await Promise.all([review(second,'approved'),review(second,'declined')]);
assert.deepEqual(decisions.map(x=>x.status).sort(),[200,409]);
assert.equal((await student()).data.request.status,'approved');
const [a,b]=await Promise.all([student('POST',{action:'collect'}),student('POST',{action:'collect'})]);
assert.equal(a.status,200);assert.equal(b.status,200);assert.equal(a.data.code,b.data.code);assert.equal(a.data.code.length,48);
assert.equal((await request('/api/chat/session',{cookie})).status,200,'collection preserves current chat');
const record=await env.DB.prepare('SELECT content FROM prototype_settings WHERE id=?').bind('code-request:'+target.id).first();assert.equal(record.content.includes(a.data.code),false);
const used=await request('/api/chat/session',{method:'POST',data:{code:a.data.code}});assert.equal(used.status,200);
assert.equal((await request('/api/chat/session',{method:'POST',data:{code:a.data.code}})).status,401);
assert.equal((await request('/api/chat/session',{cookie})).status,401);
const newCookie=used.headers.get('set-cookie').split(';')[0];
assert.equal((await request('/api/chat/request-code',{method:'POST',cookie:newCookie,data:{action:'collect'}})).status,409);
console.log('Replacement code checks passed: authenticated requests, CSRF, admin-only review, duplicate suppression, atomic review, decline, recoverable collection, hashed storage, session continuity and single-use redemption.');
